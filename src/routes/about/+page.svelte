    <h2>Tentang Kami</h2>
    <p>CekData.ai adalah alat bantu berbasis kecerdasan artifisial yang dirancang untuk membantu jurnalis memverifikasi klaim publik dengan menggunakan data resmi. Fokus utamanya adalah mendukung pemeriksaan fakta atas pernyataan yang berbasis angka, statistik, dan indikator yang dapat diuji dengan sumber terpercaya.</p>
    <p>CekData.ai dikembangkan oleh Indonesia Data Journalism Network (IDJN), sebuah organisasi yang berfokus pada pengembangan jurnalisme data di Indonesia. Melalui pelatihan, kolaborasi, eksperimen, dan pengembangan alat, IDJN mendorong pemanfaatan data dalam kerja jurnalistik agar liputan menjadi lebih kuat, akurat, dan relevan bagi publik.</p>
    <p>Kami mengembangkan CekData.ai karena banyak klaim berbasis data beredar di ruang publik, sementara proses memeriksanya sering memerlukan waktu, ketelitian, dan akses pada sumber yang tidak selalu mudah ditelusuri. Data resmi sebenarnya tersedia, tetapi kerap tersebar dalam laporan panjang, sulit dicari dengan cepat, dan membutuhkan pengolahan sebelum bisa digunakan secara efektif.</p>
    <p>Melalui CekData.ai, kami ingin membuat proses verifikasi data menjadi lebih cepat, lebih akurat, dan lebih mudah diakses oleh jurnalis. Kami percaya bahwa akses yang lebih baik terhadap data resmi akan membantu memperkuat praktik pemeriksaan fakta dan jurnalisme berbasis data di Indonesia.</p>
    <br>
    <h2>Metodologi</h2>
    <p>CekData.ai menggunakan pendekatan <em>Retrieval Augmented Generation</em> (RAG), yaitu metode yang menggabungkan model bahasa dengan sistem pencarian ke basis pengetahuan yang telah dikurasi. Dengan pendekatan ini, jawaban yang dihasilkan tidak semata bergantung pada pengetahuan umum model, tetapi disusun berdasarkan data yang tersedia di dalam sistem.</p>
    <p>Saat ini, sumber data utama yang digunakan berasal dari BPS Pusat, termasuk tabel statistik dan press release. Sumber ini dipilih karena merupakan salah satu rujukan statistik resmi terbesar di Indonesia, namun belum banyak dimanfaatkan secara optimal dalam proses verifikasi jurnalistik sehari hari.</p>
    <p>Sebelum digunakan oleh sistem, data diambil dari sumber resmi, dibersihkan, dikonversi ke bentuk teks, lalu dipecah menjadi bagian bagian kecil agar dapat dicari dan diproses secara lebih presisi. Proses ini diotomasi untuk membantu sistem menemukan konteks yang paling relevan ketika pengguna mengajukan pertanyaan.</p>
    <p>Ketika pengguna mengirimkan pertanyaan, sistem akan menelusuri basis pengetahuan untuk menemukan informasi yang paling relevan, lalu menyusun jawaban berdasarkan data yang tersedia. Karena itu, CekData.ai difokuskan secara khusus untuk membantu verifikasi klaim berbasis data, bukan untuk menjawab pertanyaan umum di luar konteks tersebut.</p>
    <p>Untuk menjaga kualitas jawaban, sistem dikembangkan melalui proses evaluasi dan pengujian berkala, termasuk quality assurance terhadap prompt, pengujian acak, dan evaluasi hasil tanya jawab. Pendekatan ini dilakukan untuk meningkatkan konsistensi, presisi, dan keandalan keluaran sistem.</p>
